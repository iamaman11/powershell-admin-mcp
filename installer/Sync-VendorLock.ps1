# Regenerate or independently verify all compiled/installed tunnel pins.
[CmdletBinding()]
param([switch]$Update)
$ErrorActionPreference='Stop';Set-StrictMode -Version Latest
$repository=Split-Path -Parent $PSScriptRoot
$lockPath=Join-Path $repository 'vendor/tunnel-client.lock.json'
$lock=Get-Content -LiteralPath $lockPath -Raw|ConvertFrom-Json -AsHashtable
if($lock.Count -ne 8 -or $lock.schema -ne 1 -or $lock.name -cne 'openai/tunnel-client' -or
   $lock.version -cnotmatch '^\d+\.\d+\.\d+$' -or
   $lock.asset -cne "tunnel-client-runtime-v$($lock.version)-windows-amd64.zip" -or
   $lock.source -cne "https://github.com/openai/tunnel-client/releases/download/v$($lock.version)/$($lock.asset)" -or
   $lock.executable -cne 'tunnel-client-runtime.exe' -or
   $lock.zip_sha256 -cnotmatch '^[A-F0-9]{64}$' -or
   $lock.exe_sha256 -cnotmatch '^[A-F0-9]{64}$') {throw 'VENDOR_LOCK_INVALID'}
$cs=(@(
    '// Generated by installer/Sync-VendorLock.ps1 from vendor/tunnel-client.lock.json. Do not edit.'
    'internal static class VendorLock'
    '{'
    "    internal const string Version = `"$($lock.version)`";"
    "    internal const string ZipSource = `"$($lock.source)`";"
    "    internal const string ZipSha256 = `"$($lock.zip_sha256)`";"
    "    internal const string ExecutableSha256 = `"$($lock.exe_sha256)`";"
    '}'
) -join "`n")+"`n"
$ps=(@(
    '# Generated by installer/Sync-VendorLock.ps1 from vendor/tunnel-client.lock.json. Do not edit.'
    "`$script:VendorLockVersion = '$($lock.version)'"
    "`$script:VendorLockZipSource = '$($lock.source)'"
    "`$script:VendorLockZipSha256 = '$($lock.zip_sha256)'"
    "`$script:VendorLockExeSha256 = '$($lock.exe_sha256)'"
) -join "`n")+"`n"
$outputs=@{
    (Join-Path $repository 'src/WindowsAdminMcp/VendorLock.Generated.cs')=$cs
    (Join-Path $PSScriptRoot 'VendorLock.Generated.ps1')=$ps
}
foreach($entry in $outputs.GetEnumerator()){
    if($Update){[IO.File]::WriteAllText($entry.Key,$entry.Value,[Text.UTF8Encoding]::new($false));continue}
    if(-not(Test-Path -LiteralPath $entry.Key -PathType Leaf)){throw 'VENDOR_GENERATED_FILE_MISSING'}
    $existing=[IO.File]::ReadAllText($entry.Key).Replace("`r`n","`n")
    if($existing -cne $entry.Value){throw 'VENDOR_GENERATED_DRIFT'}
}
Write-Host $(if($Update){'VENDOR_LOCK_GENERATED=PASS'}else{'VENDOR_LOCK_VERIFIED=PASS'})
